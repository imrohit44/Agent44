
"""Deterministic provenance and taint tracking for MCP tool-call data.

This module provides a small, in-memory provenance model that Agent44 uses to
track where tool-call arguments come from and whether they are trusted.

Design rules
------------
* Provenance is *trusted metadata maintained by Agent44*. It is never accepted
  from a caller-supplied field or MCP argument as authoritative proof that data
  is trusted. A caller-controlled argument such as ``{"trusted": true}`` cannot
  promote itself to trusted status.
* There is no model, no Ollama, no expression language, and no arbitrary code
  involved in trust decisions. Every transition is deterministic.
* Trust may only be *elevated* (untrusted -> trusted) by an explicitly recorded,
  validated transition. Ordinary transformations preserve or propagate taint;
  they never silently cleanse it.
* Missing or unknown provenance is never treated as trusted.
* Records are immutable and the registry is bounded (record count, chain depth,
  parent count). Exceeding a bound fails closed.
"""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field
from enum import StrEnum


class TrustClass(StrEnum):
    """Classification of a value's provenance.

    * ``trusted`` -- from an explicitly trusted source or a validated boundary.
    * ``untrusted`` -- external / user-controlled data at an input boundary.
    * ``derived_untrusted`` -- derived from untrusted input and not yet
      explicitly sanitized or validated.
    """

    TRUSTED = "trusted"
    UNTRUSTED = "untrusted"
    DERIVED_UNTRUSTED = "derived_untrusted"


class ProvenanceError(Exception):
    """Base class for provenance failures (forged, malformed, bounded)."""


class ProvenanceLimitError(ProvenanceError):
    """Raised when a provenance record would exceed a configured bound."""


# Default bounds, chosen to keep provenance metadata small and deterministic
# while remaining sufficient for a single tool call's argument graph.
DEFAULT_MAX_RECORDS = 10_000
DEFAULT_MAX_DEPTH = 16
DEFAULT_MAX_PARENTS = 8


def _new_provenance_id() -> str:
    """Generate a stable, Agent44-owned provenance identifier.

    Callers never supply provenance ids; they are always generated here so that
    a caller cannot forge a trusted reference.
    """
    return uuid.uuid4().hex


@dataclass(frozen=True)
class ProvenanceRecord:
    """An immutable, typed provenance record for one value.

    Attributes:
        provenance_id: Stable identifier generated by Agent44.
        trust_class: Effective trust classification.
        source_category: Human-readable origin (e.g. ``external_argument``,
            ``trusted_internal``, ``derived``, ``validated_transition``).
        parent_ids: Provenance identifiers of the values this was derived from.
        validation_transition: Identifier of an explicit validation/sanitization
            transition, if this record was elevated through one.
        boundary: The trust boundary that classified or derived this value.
        depth: Chain depth (1 for a boundary record, deeper for derived values).
        timestamp: Monotonic-ish creation time (seconds since epoch).
    """

    provenance_id: str
    trust_class: TrustClass
    source_category: str
    parent_ids: tuple[str, ...]
    validation_transition: str | None = None
    boundary: str = ""
    depth: int = 1
    timestamp: float = field(default_factory=time.time)


class ProvenanceRegistry:
    """In-memory store of provenance records for a single tool call.

    The registry is deliberately short-lived: one registry per tool call keeps
    metadata bounded and avoids any implicit cross-call taint carryover.
    Cross-call propagation is intentionally out of scope for this phase and is
    documented as a limitation.
    """

    def __init__(
        self,
        *,
        max_records: int = DEFAULT_MAX_RECORDS,
        max_depth: int = DEFAULT_MAX_DEPTH,
        max_parents: int = DEFAULT_MAX_PARENTS,
    ) -> None:
        if max_records <= 0 or max_depth <= 0 or max_parents <= 0:
            raise ValueError("provenance bounds must be positive")
        self.max_records = max_records
        self.max_depth = max_depth
        self.max_parents = max_parents
        self._records: dict[str, ProvenanceRecord] = {}

    # ------------------------------------------------------------------ creation

    def classify_external(self, *, boundary: str = "external_argument") -> str:
        """Mark externally controlled data as untrusted at an input boundary.

        Returns a fresh provenance id. This is the default classification for
        every incoming tool-call argument.
        """
        return self._create(
            trust_class=TrustClass.UNTRUSTED,
            source_category="external_argument",
            parent_ids=(),
            boundary=boundary,
        )

    def classify_trusted(
        self,
        *,
        boundary: str = "trusted_internal",
        source_category: str = "trusted_internal",
    ) -> str:
        """Create a trusted provenance record at an explicit trust boundary.

        Only Agent44 (or an explicitly configured validator) may call this.
        Caller-supplied data is never classified here.
        """
        return self._create(
            trust_class=TrustClass.TRUSTED,
            source_category=source_category,
            parent_ids=(),
            boundary=boundary,
        )


    def derive(
        self,
        parent_ids: tuple[str, ...],
        *,
        boundary: str = "derived",
        source_category: str = "derived",
    ) -> str:
        """Derive provenance from one or more parent values.

        Taint propagation rules:
        * If any parent is missing, unknown, untrusted, or derived-untrusted,
          the result is ``derived_untrusted`` -- taint is retained and never
          silently discarded.
        * If every parent is trusted, the result is ``trusted`` (preservation,
          not elevation: nothing becomes more trusted than it already was).
        * Trust elevation (untrusted -> trusted) is NOT possible here; use
          :meth:`validate_transition` for that.

        Unknown parent ids are treated as untrusted so a forged or missing
        reference can never grant trust.
        """
        if len(parent_ids) > self.max_parents:
            raise ProvenanceLimitError(
                f"too many parent provenance references ({len(parent_ids)} > "
                f"{self.max_parents})"
            )
        if len(set(parent_ids)) != len(parent_ids):
            raise ProvenanceLimitError("duplicate parent provenance references")

        parent_records = [self._records.get(pid) for pid in parent_ids]
        max_parent_depth = 0
        for rec in parent_records:
            if rec is not None:
                max_parent_depth = max(max_parent_depth, rec.depth)

        # Any missing/unknown parent contributes untrusted taint. Any present
        # non-trusted parent taints the result. Only all-trusted parents keep
        # the result trusted (preservation).
        if any(
            rec is None or rec.trust_class is not TrustClass.TRUSTED
            for rec in parent_records
        ):
            trust_class = TrustClass.DERIVED_UNTRUSTED
        else:
            trust_class = TrustClass.TRUSTED

        depth = max_parent_depth + 1
        if depth > self.max_depth:
            raise ProvenanceLimitError(
                f"provenance chain depth {depth} exceeds bound {self.max_depth}"
            )

        return self._create(
            trust_class=trust_class,
            source_category=source_category,
            parent_ids=tuple(parent_ids),
            boundary=boundary,
            depth=depth,
        )

    def validate_transition(
        self,
        provenance_id: str,
        transition_id: str,
        *,
        boundary: str = "validated_transition",
        permitted_use: str | None = None,
    ) -> str:
        """Record an explicitly authorized validation transition.

        Creates a new ``trusted`` record derived from ``provenance_id``,
        stamped with ``validation_transition=transition_id``. This is the *only*
        operation that elevates untrusted or derived-untrusted data to trusted,
        and it is explicit about what was validated (``transition_id``), which
        boundary performed it (``boundary``), and which downstream use is
        permitted (``permitted_use``).

        The elevation applies only to the newly derived record; other values
        derived from the same untrusted parent remain tainted.

        Returns the new provenance id.
        Raises :class:`ProvenanceError` if the source record is unknown.
        """
        source = self._records.get(provenance_id)
        if source is None:
            raise ProvenanceError(
                f"unknown provenance id {provenance_id!r} for validation transition"
            )
        if not transition_id or not transition_id.strip():
            raise ValueError("transition_id must be non-empty")
        depth = source.depth + 1
        if depth > self.max_depth:
            raise ProvenanceLimitError(
                f"provenance chain depth {depth} exceeds bound {self.max_depth}"
            )
        return self._create(
            trust_class=TrustClass.TRUSTED,
            source_category="validated_transition",
            parent_ids=(provenance_id,),
            validation_transition=transition_id.strip(),
            boundary=boundary,
            depth=depth,
        )


    # ------------------------------------------------------------------ queries

    def effective_trust(self, provenance_id: str | None) -> TrustClass:
        """Return the effective trust class for a provenance reference.

        ``None``, missing, unknown, or forged ids are never trusted: they
        resolve to ``untrusted`` so that any policy requiring trust denies.
        """
        if provenance_id is None:
            return TrustClass.UNTRUSTED
        record = self._records.get(provenance_id)
        if record is None:
            return TrustClass.UNTRUSTED
        return record.trust_class

    def get_record(self, provenance_id: str | None) -> ProvenanceRecord | None:
        """Return the record for an id, or ``None`` when missing/unknown."""
        if provenance_id is None:
            return None
        return self._records.get(provenance_id)

    # ------------------------------------------------------------------ internals

    def _create(
        self,
        *,
        trust_class: TrustClass,
        source_category: str,
        parent_ids: tuple[str, ...],
        validation_transition: str | None = None,
        boundary: str = "",
        depth: int = 1,
    ) -> str:
        if len(self._records) >= self.max_records:
            raise ProvenanceLimitError(
                f"provenance record bound {self.max_records} reached"
            )
        provenance_id = _new_provenance_id()
        record = ProvenanceRecord(
            provenance_id=provenance_id,
            trust_class=trust_class,
            source_category=source_category,
            parent_ids=parent_ids,
            validation_transition=validation_transition,
            boundary=boundary,
            depth=depth,
        )
        self._records[provenance_id] = record
        return provenance_id

    def __len__(self) -> int:
        return len(self._records)

    def __repr__(self) -> str:
        return f"ProvenanceRegistry(records={len(self._records)})"


@dataclass(frozen=True)
class ProvenanceContext:
    """Per-call provenance metadata, kept separate from business arguments.

    Maps argument name -> provenance id (or ``None`` when no provenance has been
    established). Maintained by Agent44; never accepted from caller-controlled
    arguments as authoritative.
    """

    registry: ProvenanceRegistry
    values: dict[str, str | None] = field(default_factory=dict)

    def provenance_id_for(self, argument_name: str) -> str | None:
        return self.values.get(argument_name)

    def with_argument(
        self, argument_name: str, provenance_id: str | None
    ) -> ProvenanceContext:
        """Return a copy associating ``argument_name`` with ``provenance_id``."""
        values = dict(self.values)
        values[argument_name] = provenance_id
        return ProvenanceContext(registry=self.registry, values=values)

